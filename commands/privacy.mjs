// Render the data-protection pages that the published site needs:
//
//   privacy.html                 the Art. 14 information notice
//   scanner.html                 "one of our nodes connected to you" — the page
//                                a sysadmin lands on after a reverse lookup
//   .well-known/security.txt     RFC 9116 contact record
//
// Why a notice at all: we collect data about people who never visited the site,
// so GDPR Art. 14 applies rather than Art. 13. Notifying each peer individually
// is impossible (the DHT carries no such channel and we hold no contact
// details), which is exactly the case Art. 14(5)(b) covers — but that exemption
// is conditional on publishing the information instead. This page IS that
// condition being met, not a courtesy.
//
// The scanner page follows the convention set by Shodan, Censys and RIPE Atlas:
// point the crawler IP's reverse DNS at a page that explains who is connecting
// and how to be excluded, so the answer reaches an annoyed sysadmin before a
// complaint does.

// ---------------------------------------------------------------------------
// The one site-specific value: an email address, and nothing else. The pages
// deliberately do NOT identify an operator or carry a site URL — every link
// between them is relative, so the pages work from any host without being
// configured for one. This address is the abuse / exclusion contact, which the
// scanner page and security.txt need in order to do their job at all (RFC 9116
// makes `Contact` mandatory, and "write to us to be excluded" without an
// address is not an offer). Fill it in before publishing.
// ---------------------------------------------------------------------------
const CONTACT_EMAIL = '[contact]';

const PLACEHOLDER = /^\[.*\]$/;

// Data-protection facts that are properties of the code, kept here so the page
// and the repo docs can't drift apart silently.
const RETENTION_OBSERVATION_DAYS = 14;
const RETENTION_NODE_HOURS = 72;
const SALT_ROTATION = 'monthly';

const TILE_PROVIDER = 'CARTO (basemaps.cartocdn.com)';

